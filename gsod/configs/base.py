"""Base configuration for the GS slot model.

Each slot is decoded into a fixed number of Gaussians by the decoder
class passed to ``build_model`` (``AttentionDecoder`` by default).

``PrimordiaConfig`` and ``Clevr567Config`` inherit these fields and only
override dataset-specific values.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from gsod.configs.loss import LossConfig
from gsod.utils.paths import default_out_dir


@dataclass
class BaseConfig:
    # --- model -----------------------------------------------------------------
    # Side length of the square image passed to the encoder.
    input_size: int = 64
    # Channel width of encoder features and slot latents.
    z_dim: int = 64
    # Number of slots K, all interchangeable (objects and background).
    num_slots: int = 6
    # Number of slot-attention refinement iterations.
    attn_iter: int = 3
    # Number of Gaussians generated by each slot.
    gaussians_per_slot: int = 512
    # Hidden width of the decoder (MLP width, or attention width d_model).
    decoder_hidden_dim: int = 128
    # Side of the 2D reconstruction of each encoded view (model/aux_decoder.py).
    aux2d_size: int = 64
    # Views encoded in training for the 2D reconstruction (view 0 first);
    # 1 = the encoder sees one image, as at inference.
    aux2d_views: int = 1
    # Near clipping distance used when projecting Gaussians.
    near: float = 0.1

    # --- optimisation ----------------------------------------------------------
    # Number of optimisation steps (scenes_per_step scenes each).
    steps: int = 10_000
    # Adam learning rate: linear warm-up over lr_warmup_steps, then halved
    # every lr_half_life steps (Slot Attention's schedule).
    lr: float = 3e-4
    lr_warmup_steps: int = 5_000
    lr_half_life: int = 100_000
    # Scenes whose gradients are accumulated per optimisation step.
    scenes_per_step: int = 1
    # Gradient-norm clipping (0 = off).
    grad_clip: float = 1.0
    # Seed for torch, scene/view sampling, and model initialisation.
    seed: int = 0
    # Print a training log line every N steps.
    log_every: int = 100
    # Run validation on the val split every N steps.
    eval_every: int = 2_000
    # Write an iter_<step> checkpoint every N steps.
    save_every: int = 5_000
    # DataLoader worker processes.
    num_workers: int = 4
    # Loss term weights.
    loss: LossConfig = field(default_factory=LossConfig)

    # --- data ------------------------------------------------------------------
    # Dataset format: "primordia" or "clevr567".
    dataset_mode: str = "primordia"
    # CLEVR-567 loader only (Primordia reads all of these from meta.json):
    # square image size (uORF trains at 128x128),
    dataset_image_size: int = 128
    # uORF's focal ratio (fx/W, fy/H) for its 320x240 renders,
    dataset_focal_ratio: tuple[float, float] = (350.0 / 320.0, 350.0 / 240.0)
    # views loaded per scene (uORF uses four),
    n_views: int = 4
    # fraction of the training root held out for validation.
    val_fraction: float = 0.1

    # Dataset root. Primordia expects meta.json; CLEVR-567 expects the flat
    # uORF layout with *scNNNN*.png and *_RT.txt files.
    data_root: str = "data/primordia"
    # Root of the test split, if it is a separate directory (CLEVR-567);
    # None: the test split lives in data_root (Primordia).
    test_root: str | None = None
    # Scene priors (SceneGenConfig keys) for datasets without meta.json; they
    # set the frame bounds (scene size and reach beyond the cameras), which are
    # not stored in checkpoints, so train and test must use the same values.
    scene_prior: dict | None = None
    # Directory for checkpoints and their *_state.json files.
    out_dir: str = field(default_factory=lambda: default_out_dir("run"))
