"""Datasets used by the GS slot model.

Primordia is generated by this repository into ``data/<name>/`` with a
``meta.json``. CLEVR-567 is the flat uORF layout (``*sc0000*.png`` plus
``*_RT.txt`` files). Both loaders expose one item per scene.
"""

from __future__ import annotations

from pathlib import Path

from gsod.data_generator.io import load_meta
from gsod.data_loader.clevr567 import CLEVR567_FOCAL_RATIO, Clevr567Scenes
from gsod.data_loader.primordia import PrimordiaScenes, hit_distance_to_depth
from gsod.data_loader.gt_masks import WithGTMasks

__all__ = [
    "Clevr567Scenes",
    "CLEVR567_FOCAL_RATIO",
    "PrimordiaScenes",
    "hit_distance_to_depth",
    "make_dataset",
    "dataset_meta",
    "WithGTMasks",
]


def make_dataset(
    root: str | Path,
    split: str,
    *,
    dataset_mode: str = "primordia",
    image_size: int | tuple[int, int] = 128,
    focal_ratio: tuple[float, float] = CLEVR567_FOCAL_RATIO,
    n_views: int = 4,
    val_fraction: float = 0.1,
    seed: int = 0,
    load_masks: bool = False,
    load_depth: bool = False,
):
    """Build the dataset for ``split`` using the configured format."""
    if dataset_mode == "primordia":
        return PrimordiaScenes(root, split)
    if dataset_mode == "clevr567":
        return Clevr567Scenes(
            root,
            split,
            image_size=image_size,
            focal_ratio=focal_ratio,
            n_views=n_views,
            val_fraction=val_fraction,
            seed=seed,
            load_masks=load_masks,
            load_depth=load_depth,
        )
    raise ValueError(
        f"unknown dataset_mode {dataset_mode!r}; use 'primordia' or 'clevr567'"
    )


def dataset_meta(
    root: str | Path,
    *,
    dataset_mode: str = "primordia",
    image_size: int | tuple[int, int] = 128,
    focal_ratio: tuple[float, float] = CLEVR567_FOCAL_RATIO,
) -> dict:
    """Return the metadata needed by ``build_model`` without loading images."""
    if dataset_mode == "primordia":
        return load_meta(root)
    if dataset_mode == "clevr567":
        if isinstance(image_size, int):
            image_size = (image_size, image_size)
        return {
            "dataset": "clevr567",
            "image_size": [int(image_size[0]), int(image_size[1])],
            "focal_ratio": [float(focal_ratio[0]), float(focal_ratio[1])],
        }
    raise ValueError(
        f"unknown dataset_mode {dataset_mode!r}; use 'primordia' or 'clevr567'"
    )
